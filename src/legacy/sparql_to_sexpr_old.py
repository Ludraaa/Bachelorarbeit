def tokenize_sexp(s: str) -> list[str]:
    return re.findall(
        r'\(|\)|\[|\]'           # parens and brackets
        r'|"[^"]*"\^\^[^\s()\[\]]+'  # typed literals: "val"^^type
        r'|"[^"]*"'              # plain strings
        r'|[^\s()\[\]]+',        # everything else
        s
    )

def parse_tokens(tokens: list[str], i: int) -> tuple:
    if tokens[i] == '(':
        i += 1
        children = []
        while tokens[i] != ')':
            child, i = parse_tokens(tokens, i)
            children.append(child)
        return children, i + 1
    elif tokens[i] == '[':
        i += 1
        children = []
        while tokens[i] != ']':
            child, i = parse_tokens(tokens, i)
            children.append(child)
        return children, i + 1
    else:
        return tokens[i], i + 1


def parse_sexp(s: str) -> list:
    tokens = tokenize_sexp(s.strip())
    result, _ = parse_tokens(tokens, 0)
    return result


