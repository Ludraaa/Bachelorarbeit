def is_lang_filter(node) -> bool:
    if not isinstance(node, list) or len(node) != 3:
        return False
    return (node[0] == '=' 
            and isinstance(node[1], list) 
            and node[1][0] == 'lang'
            and node[2] == '"en"')  # only strip English lang filters


def extract_prefix_map(ast):
    prefix_map = COMMON_PREFIXES.copy()

    if isinstance(ast, list) and ast[0] == 'prefix':
        for p in ast[1]:
            prefix = p[0].rstrip(':')
            uri = p[1][1:-1]  # strip <>
            prefix_map[prefix] = uri

    return prefix_map


def normalize_iri(token: str, prefix_map: dict) -> str:
    # blank nodes generated by Jena for [] patterns
    if token.startswith('??'):
        return '[]'

    # already full IRI
    if token.startswith("<") and token.endswith(">"):
        return token

    # variable
    if token.startswith("?"):
        return token

    # literal (including typed)
    if token.startswith('"'):
        if '^^' in token:
            val, typ = token.split('^^', 1)
            if typ.startswith("<"):
                return f"{val}^^{typ}"
            if ":" in typ:
                prefix, local = typ.split(":", 1)
                if prefix in prefix_map:
                    return f'{val}^^<{prefix_map[prefix]}{local}>'
        return token

    # prefixed IRI
    if ":" in token:
        prefix, local = token.split(":", 1)
        if prefix in prefix_map:
            return f"<{prefix_map[prefix]}{local}>"

    return token


